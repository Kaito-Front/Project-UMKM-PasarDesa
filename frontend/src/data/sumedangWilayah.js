/**
 * Mengambil daftar desa berdasarkan nama kecamatan
 */
export function getDesaByKecamatan(kecamatanName) {
  if (!kecamatanName) return [];
  const cleanName = kecamatanName.startsWith('Kecamatan ') ? kecamatanName : `Kecamatan ${kecamatanName}`;
  return SUMEDANG_WILAYAH[cleanName] || [];
}

/**
 * Mencari desa/kelurahan di seluruh Sumedang berdasarkan kata kunci
 */
export function searchDesaSumedang(keyword, limit = 8) {
  if (!keyword || !keyword.trim()) return [];
  const q = keyword.toLowerCase().trim();
  return ALL_SUMEDANG_DESA.filter((d) =>
    d.desa.toLowerCase().includes(q) ||
    d.kecamatan.toLowerCase().includes(q)
  ).slice(0, limit);
}
